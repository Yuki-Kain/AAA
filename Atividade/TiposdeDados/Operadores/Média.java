package TiposdeDados.Operadores;
public class Média {
    public static void main(String[] args) {
        double nota1 = 8.0;
        double nota2 = 7.5;
        double nota3 = 4.5;
        double nota4 = 9.0;

        double media = (nota1 + nota2 + nota3 + nota4) / 4.0;

        System.out.println("A média das notas é: " + media);
    }
}